"""Derive the two-organization run scripts (stage S10, 11/05) from the final single-host ones.

srv_run_evm6w2o.sh = srv_run_evm6w.sh plus: the harness built with the two-organization overlay
(patch/twoorg/overlay.json: -extra-endorsers adds org2's endorser, built like org1's, in the same process),
the namespace from NS (default basic; basic2of2 has the policy AND(Org1, Org2)), the re-execution service
reading that namespace, and the post-run checks on that namespace's table. With NS unset and no
EXTRA_ENDORSERS it runs exactly what srv_run_evm6w.sh runs (same harness code path, overlay included).
"""
import io, os

H = os.path.dirname(os.path.abspath(__file__))


def derive(src, dst, reps, head):
    s = io.open(os.path.join(H, src), encoding="utf-8").read()
    for old, new in reps:
        assert s.count(old) == 1, (src, old)
        s = s.replace(old, new)
    lines = s.split("\n")
    lines.insert(1, head)
    io.open(os.path.join(H, dst), "w", encoding="utf-8", newline="\n").write("\n".join(lines))


derive("srv_run_evm6w.sh", "srv_run_evm6w2o.sh", [
    ("go test -timeout 1400s -tags=perf ", "go test -timeout 1400s -tags=perf -overlay $D/patch/${OVERLAY:-twoorg}/overlay.json "),
    ("-namespace basic ", "-namespace ${NS:-basic} ${EXTRA_ENDORSERS:+-extra-endorsers $EXTRA_ENDORSERS} ${RETRY_MISMATCH:+-retry-mismatch} "),
    ('/usr/local/bin/d16reexec $REEXEC_ARGS > /tmp/d16reexec.log', '/usr/local/bin/d16reexec $REEXEC_ARGS -ns=${NS:-basic} > /tmp/d16reexec.log'),
    ("$(bash $D/scripts/srv_statecheck.sh $LABEL)", "$(NS=${NS:-basic} bash $D/scripts/srv_statecheck_ns.sh $LABEL)"),
    ("$(bash $D/scripts/srv_sbcheck.sh $LABEL)", "$(NS=${NS:-basic} bash $D/scripts/srv_sbcheck_ns.sh $LABEL)"),
], "# srv_run_evm6w2o.sh (11/05, stage S10): srv_run_evm6w.sh with the two-organization harness overlay; env NS (namespace,\n"
   "# default basic), EXTRA_ENDORSERS (e.g. fabx-2of2-org2.yaml), OVERLAY (patch dir, default twoorg; twoorg_r adds\n"
   "# -retry-mismatch) and RETRY_MISMATCH=1; generated by make_twoorg_scripts.py")
derive("srv_statecheck.sh", "srv_statecheck_ns.sh", [
    ("FROM ns_basic WHERE", "FROM ns_${NS:-basic} WHERE"),
], "# srv_statecheck_ns.sh (11/05): srv_statecheck.sh on the table of namespace $NS (default basic)")
derive("srv_sbcheck.sh", "srv_sbcheck_ns.sh", [
    ("FROM ns_basic WHERE", "FROM ns_${NS:-basic} WHERE"),
], "# srv_sbcheck_ns.sh (11/05): srv_sbcheck.sh on the table of namespace $NS (default basic)")
print("ok")
