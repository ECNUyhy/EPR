"""Third version of the refinement stages (11/05).

One rule and one engine for every remaining refinement, the rule of S14, S10c and S16:
  - above the peak: the quarter points of [best sustained rate, next tested rate above it], ascending until the first
    run that fails the criterion (no other early stop);
  - below a saturated peak (goodput < 90% of the offered rate): descending, until the first sustained run whose goodput
    is at least 95% of its offered rate;
  - a sweep that sustained its highest tested rate is extended by 10% steps until a run fails, then refined as above;
  - rounds repeat (at most 4) while the best point moves.
Stages (files in queue_extra_1104/):
  85b_s15a2.sh  continues S15a, whose first version also stopped at a sustained but saturated run, and later at a run
                without gain; it finishes each original interval and refines around moved peaks (logs s15a + s15a2);
  90_s15b.sh    the baseline sweeps shown in Fig. 8/10 that S14 and S15a do not cover, including sweeps that ended
                while still sustained (held back on the server as scripts/s15b_real.sh.hold until the night);
  92_s15e.sh    EPR's own sweeps with a gap: USDT and DEX 64 (both modes), the Zipf 0, 0.6, 0.9, 1.2 and SmallBank
                0.6 skews (also held for the night as scripts/s15e_real.sh.hold).
Only sweeps whose peak a figure or the text shows: Fig. 8 and Fig. 10 (with retries; depgraph without, it never
aborts), Fig. 11a (EPR only: its no-retry peaks), and S14's baselines (done).
usage (local, before q1103_s15a.txt is pulled): python make_s15v3.py
"""
