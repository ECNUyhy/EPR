def write(fname, name, x, what, keys, logs, downs=True):
    tab = "\n".join(f"{m} {s} {w} {want[(m, s, w)][0]} {want[(m, s, w)][1]} {want[(m, s, w)][2]} "
                    f"{','.join(map(str, want[(m, s, w)][3])) or '-'} "
                    f"{(','.join(map(str, want[(m, s, w)][4])) or '-') if downs else '-'}" for m, s, w in keys)
    txt = (ENGINE.replace("@NAME@", name).replace("@WHAT@", what).replace("@X@", x).replace("@TAB@", tab)
           .replace("@LOGS@", " ".join(f"$D/logs/q1103_{l}.txt" for l in logs)).replace("@UP@", name.upper()))
    io.open(os.path.join(H, "queue_extra_1104", fname), "w", encoding="utf-8", newline="\n").write(txt)
    print(fname, len(keys), "sweeps")


