def group(pts, pk):
    """(best rate, best goodput, next tested rate above or 0, up quarter points, down quarter points (descending))"""
    best = next(r for r, p in pts.items() if p["goodput"] == pk)
    above = sorted(r for r in pts if r > best)
    below = sorted(r for r in pts if r < best)
    up = []
    if above and above[0] / best > 1.07:
        up = [r for r in (best + (above[0] - best) * k // 4 for k in (1, 2, 3)) if r not in pts and r > best]
    down = []
    if pk < 0.9 * best and below and best / below[-1] > 1.07:
        down = [r for r in (below[-1] + (best - below[-1]) * k // 4 for k in (3, 2, 1)) if r not in pts and r < best]
    return best, int(round(pk)), above[0] if above else 0, up, down, not above


want = {}


def add(key, pts, peakf, mode):
    if not pts or key in want:
        return
    pk = peakf(pts, mode)
    if not pk:
        return
    best, gb, nx, up, down, top = group(pts, pk)
    if up or down or top:
        want[key] = (best, gb, nx, up, down)


