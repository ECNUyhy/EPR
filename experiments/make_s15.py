"""Generate stages S15a / S15b (11/05): refinement of every remaining baseline sweep of the paper's figures.

S14 refines the baselines that bound EPR's leads. The rest of the baseline sweeps (Fabric-X, depgraph, FabricSharp,
Fabric++, and a few XOX/HTFabric skews) were swept with coarse steps and never refined, so the Setup's "refines around
the best sustained rate, for all schemes alike" does not hold for them, and several numbers the text quotes depend on
their peaks (71x Fabric-X and 147x depgraph on USDC, 55x Fabric-X on USDT, "no more than 450 tx/s", "an order of
magnitude", "under 10 tx/s", "below 4k tx/s", "40--300x less").
Rule as refine_points.py: the quarter points of [peak rate, next tested rate] (ascending, stopping at the first that
fails the criterion), and, if the peak rate is saturated (goodput < 90% of the offered rate), also the quarter points of
[previous tested rate, peak rate].
  S15a: the sweeps behind a number of the text; S15b: all others.
usage (local, from scripts/server): python make_s15.py  ->  queue_extra_1104/85_s15a.sh, 90_s15b.sh
"""
import io, os, runpy, sys

H = os.path.dirname(os.path.abspath(__file__))
os.environ["EPR_FINAL"] = "w:q1103/q1103_s7a,q1103/q1103_s7b,q1103/q1103_s9"
os.chdir(os.path.join(H, "..", "analysis"))
sys.argv = ["x"]
g = runpy.run_path("final_fill.py", run_name="notmain")
S, O, L, BASE = g["S"], g["O"], g["L"], g["BASE"]
p47, extra = g["p47"], g["extra"]

S14 = set()
for line in io.open(os.path.join(H, "queue_extra_1104", "80_s14.sh"), encoding="utf-8"):
    f = line.split()
    if len(f) == 4 and f[0] in ("rk", "pk") and f[1] in BASE:
        S14.add((f[0], f[1], f[2]))

ZW = ["z0", "z0.6", "z0.8", "z0.9", "z0.99", "z1.2"]
SW = ["sb0", "sb0.6", "sb0.8", "sb1.0", "sb1.2"]
want = {}


def add(mode, s, wl, pts, peakf):
    if not pts or (mode, s, wl) in S14 or (mode, s, wl) in want:
        return
    pk = peakf(pts, mode)
    if not pk:
        return
    best = next(r for r, p in pts.items() if p["goodput"] == pk)
    above = sorted(r for r in pts if r > best)
    below = sorted(r for r in pts if r < best)
    up = []
    if above and above[0] / best > 1.07:
        up = [r for r in (best + (above[0] - best) * k // 4 for k in (1, 2, 3)) if r not in pts and r > best]
    down = []
    if pk < 0.9 * best and below:
        down = [r for r in (below[-1] + (best - below[-1]) * k // 4 for k in (3, 2, 1)) if r not in pts and r < best]
    if up or down:
        want[(mode, s, wl)] = (up, down, int(round(pk)), best, above[0] if above else 0)


# 11/05: only sweeps whose peak appears somewhere. Fig. 8 (bars) and Fig. 10 (skews) show every baseline's peak
# with retries (depgraph: its no-retry sweep, as it never aborts); Fig. 9 shows the USDC, SmallBank 1.0 and DEX 16
# sweeps; Fig. 11a shows only EPR / best baseline, and S14 covers every baseline that can be the best. So the no-retry
# sweeps of the other baselines and the 1M uniform sweeps (whose quoted values S14 covers) are not refined.
for s in BASE:
    for wl, _ in O.WORKLOADS:
        pts, m = O.points(s, wl, p47)
        add(m, s, wl, pts, S.peak)
    for wl in ZW + SW:
        m = L.mode_of(s, "rk")
        add(m, s, wl, L.skew_points(extra, s, m, wl), S.peak)

# the sweeps behind a number of the text (Fig. 9 panels, USDC/USDT multiples, SmallBank/DEX/skew statements)
TEXT = {("rk", "fifo", w) for w in ("usdc", "usdt", "sb1.0", "dex16", "z0", "z0.8", "sb0", "sb0.8")}
TEXT |= {("rk", s, w) for s in ("fs", "fpp") for w in ("usdc", "usdt", "sb0.8", "sb1.0", "sb1.2", "dex1", "dex16",
                                                       "z0", "z0.6", "sb0", "sb0.6")}
TEXT |= {("pk", "depg", w) for w in ("usdc", "usdt", "sb1.0", "dex16", "z0", "z0.8", "sb0", "sb0.8")}

HEAD = """# Stage {name} (11/05), generated by make_s15.py: refinement of the baseline sweeps {what}.
# Rule as refine_points.py: quarter points of [peak rate, next tested rate], ascending until one fails the criterion;
# if the peak rate is saturated (goodput < 90% of the offered rate), also those of [previous tested rate, peak rate].
# 11/05: only the sweeps whose peak a figure or the text shows; below a saturated peak the first unsaturated
# sustained rate ends the refinement (descending). Above the peak (second version, 11/05 noon): a run ends it when it
# fails or when its goodput does not exceed the best so far (column gb = the peak's goodput); the first version also
# stopped at a sustained but saturated run, which can stop while the goodput is still rising (Fabric-X USDC: 92 ->
# 124.8 tx/s at 137, goodput 91% of the offered rate).
XNAME={x}
saturated() {{ local g; g=$(echo "$1" | grep -oE "whole_goodput=[0-9]+" | head -1 | cut -d= -f2); [ -n "$g" ] && [ $((g * 100)) -lt $(($2 * 95)) ]; }}
gput() {{ local g; g=$(echo "$1" | grep -oE "whole_goodput=[0-9]+" | head -1 | cut -d= -f2); echo ${{g:-0}}; }}
xbody() {{
  local R=$D/scripts/srv_run_evm6w.sh
  local RXO2="rxo2 epr 1 1 oldqueue REEXEC=1 REEXEC_BIN=$D/bin/d16reexec_v2 FX_EPR_PROG=1 REEXEC_ALL=1"
  local mode sc wl up down gb g x s img vc evm q ds gen r res extra
  while read -r mode sc wl up down gb; do
    case $sc in htf2) x="$HTF2";; rxo2) x="$RXO2";; fs) x="$FS";; fpp) x="$FPP";; fifo) x="$FIFO";; depg) x="$DEPG";; esac
    set -- $x; s=$1 img=$2 vc=$3 evm=$4 q=$5; shift 5
    read -r ds gen <<< "$(dsof $wl)"
    extra=""; [ $mode = rk ] && extra="FX_RETRY=50"
    case $wl in dex*) extra="$extra OUTSTANDING=30000";; *0M) extra="$extra FX_OL_SECONDS=30 OUTSTANDING=200000";; esac
    # below a saturated peak (listed descending): the first rate that sustains unsaturated is the highest such rate
    for r in ${{down//,/ }}; do
      [ "$r" = - ] && continue
      res=$(run ${{mode}}_${{wl}}_${{s}}_r$r $img $vc $evm $q $ds $gen FX_RATE=$r "$@" $extra < /dev/null)
      if sustained "$res" $mode && ! saturated "$res" $r; then
        g=$(gput "$res"); [ $g -gt $gb ] && gb=$g; echo "REFINE_OK ${{mode}}_${{wl}}_${{s}} at r=$r" | tee -a $out; break; fi
      echo "REFINE_NEXT ${{mode}}_${{wl}}_${{s}} at r=$r" | tee -a $out
    done
    # above the peak (ascending): stop at the first rate that fails, or whose goodput does not exceed the best so far
    for r in ${{up//,/ }}; do
      [ "$r" = - ] && continue
      res=$(run ${{mode}}_${{wl}}_${{s}}_r$r $img $vc $evm $q $ds $gen FX_RATE=$r "$@" $extra < /dev/null)
      if ! sustained "$res" $mode; then echo "REFINE_STOP ${{mode}}_${{wl}}_${{s}} at r=$r" | tee -a $out; break; fi
      g=$(gput "$res")
      if [ $g -le $gb ]; then echo "REFINE_STOP ${{mode}}_${{wl}}_${{s}} at r=$r (no gain: $g <= $gb)" | tee -a $out; break; fi
      gb=$g; echo "REFINE_OK ${{mode}}_${{wl}}_${{s}} at r=$r ($g)" | tee -a $out
    done
    save
  done <<'TAB'
{tab}
TAB
  echo "{up} refinements done" | tee -a $out
}}
"""


def write(fname, name, x, what, keys):
    tab = "\n".join(f"{m} {s} {w} {','.join(map(str, want[(m, s, w)][0])) or '-'} "
                    f"{','.join(map(str, want[(m, s, w)][1])) or '-'} {want[(m, s, w)][2]}" for m, s, w in keys)
    io.open(os.path.join(H, "queue_extra_1104", fname), "w", encoding="utf-8", newline="\n").write(
        HEAD.format(name=name, x=x, what=what, tab=tab, up=name.upper()))
    n = sum(len(want[k][0]) + len(want[k][1]) for k in keys)
    print(fname, len(keys), "sweeps, at most", n, "runs")


# S15a2 (11/05 noon): continues the S15a sweeps that the first version's saturation stop ended while the goodput was
# still rising. At run time it reads S15a's log: wherever the best sustained point moved above the old peak and the
# interval [new best rate, next tested rate above it] (> 7% wide) still has unmeasured quarter points, those are run
# ascending, stopping at a failure or when the goodput no longer rises.
A2 = r'''# Stage S15a2 (11/05), generated by make_s15.py: continuation of S15a with the corrected stop rule (see 90_s15b.sh).
XNAME=s15a2
gput() { local g; g=$(echo "$1" | grep -oE "whole_goodput=[0-9]+" | head -1 | cut -d= -f2); echo ${g:-0}; }
xbody() {
  local R=$D/scripts/srv_run_evm6w.sh
  local RXO2="rxo2 epr 1 1 oldqueue REEXEC=1 REEXEC_BIN=$D/bin/d16reexec_v2 FX_EPR_PROG=1 REEXEC_ALL=1"
  local mode sc wl up gb g x s img vc evm q ds gen r res extra
  # "<mode> <scheme> <workload> <old best rate> <old best goodput> <old next rate>" for every S15a sweep
  cat > $D/logs/s15a2_groups.txt <<'TAB'
@TAB@
TAB
  python3 - $D/logs/q1103_s15a.txt $D/logs/s15a2_groups.txt > $D/logs/s15a2_list.txt <<'PY'
import re, sys
groups = [l.split() for l in open(sys.argv[2]) if l.strip()]
pts, cur = {}, None
for line in open(sys.argv[1], errors="replace"):
    if line.startswith("== "):
        m = re.match(r"== (rk|pk)_(\S+?)_([a-z0-9]+)_r(\d+) exit=", line)
        cur = (m[1], m[3], m[2], int(m[4])) if m else None
        if cur:
            pts[cur] = [None, None, None]
        continue
    if cur:
        g = re.search(r"whole_goodput=([0-9.]+) lat_ms_p50=([0-9.]+)", line)
        if g:
            pts[cur][0], pts[cur][1] = float(g[1]), float(g[2])
        c = re.search(r"GOODPUT .*processed=(\d+)/\d+ success=(\d+)", line)
        if c and int(c[1]) > 0:
            pts[cur][2] = int(c[2]) / int(c[1])
for mode, s, wl, br, bg, nx in groups:
    br, bg, nx = int(br), float(bg), int(nx)
    new = {r: p for (m, sc, w, r), p in pts.items() if (m, sc, w) == (mode, s, wl)}
    ok = lambda p: p[0] is not None and p[1] is not None and p[1] <= 2000 and (mode == "pk" or (p[2] or 0) >= 0.95)
    best_r, best_g = br, bg
    for r, p in new.items():
        if ok(p) and p[0] > best_g:
            best_r, best_g = r, p[0]
    if best_r == br:
        continue
    tested = set(new) | {br} | ({nx} if nx else set())
    above = sorted(r for r in tested if r > best_r)
    nxt = above[0] if above else int(best_r * 1.25)
    if nxt / best_r <= 1.07:
        continue
    up = [r for r in (best_r + (nxt - best_r) * k // 4 for k in (1, 2, 3)) if r not in tested and r > best_r]
    if up:
        print(mode, s, wl, ",".join(map(str, up)), int(best_g))
PY
  echo "S15A2 continuations: $(tr '\n' ';' < $D/logs/s15a2_list.txt)" | tee -a $out
  while read -r mode sc wl up gb; do
    case $sc in htf2) x="$HTF2";; rxo2) x="$RXO2";; fs) x="$FS";; fpp) x="$FPP";; fifo) x="$FIFO";; depg) x="$DEPG";; *) continue;; esac
    set -- $x; s=$1 img=$2 vc=$3 evm=$4 q=$5; shift 5
    read -r ds gen <<< "$(dsof $wl)"
    extra=""; [ $mode = rk ] && extra="FX_RETRY=50"
    case $wl in dex*) extra="$extra OUTSTANDING=30000";; esac
    for r in ${up//,/ }; do
      res=$(run ${mode}_${wl}_${s}_r$r $img $vc $evm $q $ds $gen FX_RATE=$r "$@" $extra < /dev/null)
      if ! sustained "$res" $mode; then echo "REFINE_STOP ${mode}_${wl}_${s} at r=$r" | tee -a $out; break; fi
      g=$(gput "$res")
      if [ $g -le $gb ]; then echo "REFINE_STOP ${mode}_${wl}_${s} at r=$r (no gain: $g <= $gb)" | tee -a $out; break; fi
      gb=$g; echo "REFINE_OK ${mode}_${wl}_${s} at r=$r ($g)" | tee -a $out
    done
    save
  done < $D/logs/s15a2_list.txt
  echo "S15A2 refinements done" | tee -a $out
}
'''

order = lambda k: (k[0] != "rk", k[1], k[2])
a = sorted((k for k in want if k in TEXT), key=order)
b = sorted((k for k in want if k not in TEXT), key=order)
if "--s15a" in sys.argv:  # first version only (11/05 morning); the running S15a must not be regenerated
    write("85_s15a.sh", "S15a", "s15a", "behind a number of the text", a)
write("90_s15b.sh", "S15b", "s15b", "not covered by S14 and S15a (Setup: refinement for all schemes alike)", b)
tab2 = "\n".join(f"{m} {s} {w} {want[(m, s, w)][3]} {want[(m, s, w)][2]} {want[(m, s, w)][4]}" for m, s, w in a)
io.open(os.path.join(H, "queue_extra_1104", "85b_s15a2.sh"), "w", encoding="utf-8", newline="\n").write(
    A2.replace("@TAB@", tab2))
print("85b_s15a2.sh", len(a), "groups checked at run time")
